import json
import time
from typing import Dict, Any

class ResearchReportGenerator:
    """Generates traceable, transparent, and exportable research reports for clinical MRI studies."""

    def generate_report(
        self,
        study_id: str,
        mri_meta: Dict[str, Any],
        lesion_metrics: Dict[str, Any],
        roi_metrics: Dict[str, Any],
        prediction: Dict[str, Any],
    ) -> Dict[str, Any]:
        """Generate complete structured research report."""
        timestamp = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime())

        report_data = {
            "report_id": f"REP_{study_id}_{int(time.time())}",
            "study_id": study_id,
            "generated_at": timestamp,
            "application": "NeuroLens AI (v1.0.0)",
            "subtitle": "ROI-Based Brain MRI Analysis for Aphasia-Related Language Impairment Prediction",
            "study_geometry": {
                "dimensions": mri_meta.get("dimensions", {}),
                "voxel_dimensions_mm": mri_meta.get("voxel_dims_mm", []),
                "voxel_volume_cm3": mri_meta.get("voxel_volume_cm3", 0.0),
                "orientation": mri_meta.get("orientation", []),
            },
            "lesion_morphometry": {
                "total_lesion_volume_cm3": lesion_metrics.get("volume_cm3", 0.0),
                "total_lesion_volume_mm3": lesion_metrics.get("volume_mm3", 0.0),
                "total_lesion_voxels": lesion_metrics.get("voxel_count", 0),
                "laterality_index": lesion_metrics.get("laterality_index", 0.0),
                "laterality_label": lesion_metrics.get("laterality_label", "Unknown"),
                "left_hemisphere_vol_cm3": lesion_metrics.get("left_hemisphere_vol_cm3", 0.0),
                "right_hemisphere_vol_cm3": lesion_metrics.get("right_hemisphere_vol_cm3", 0.0),
                "center_of_gravity_mni": lesion_metrics.get("center_of_gravity_mni", [0, 0, 0]),
            },
            "roi_analysis": {
                "atlas": roi_metrics.get("atlas", {}).get("atlas_name", "Harvard-Oxford Cortical Language Atlas"),
                "network_summary": roi_metrics.get("network_summary", {}),
                "regions": roi_metrics.get("region_measurements", []),
            },
            "predictive_model_evaluation": {
                "model_version": prediction.get("model_version"),
                "model_type": prediction.get("model_type"),
                "feature_set": prediction.get("feature_set"),
                "predicted_wab_aq": prediction.get("predicted_wab_aq"),
                "uncertainty_interval_95": prediction.get("uncertainty_interval_95"),
                "impairment_category": prediction.get("impairment_category"),
                "impairment_severity": prediction.get("impairment_severity"),
                "clinical_implication": prediction.get("clinical_implication"),
                "top_feature_contributions": prediction.get("feature_contributions", []),
            },
            "scientific_disclaimer": (
                "RESEARCH AND EDUCATIONAL USE ONLY: NeuroLens AI is an academic research prototype. "
                "Predictions and volumetric findings are generated by machine learning models trained on "
                "research cohorts (e.g., Aphasia Recovery Cohort) and do not constitute an official medical diagnosis "
                "or clinical treatment plan. Clinical speech-language pathology evaluation is mandatory for patient care."
            ),
            "citations": [
                "Gibson M, et al. The Aphasia Recovery Cohort, an open-source chronic stroke repository. Sci Data. 2024;11(1):981.",
                "Kertesz A. Western Aphasia Battery - Revised (WAB-R). Pearson; 2006.",
                "Frazier JA, et al. Structural and functional imaging in chronic post-stroke aphasia. Neuroimage Clin. 2020.",
            ],
        }

        return report_data

    def generate_html_view(self, report_data: Dict[str, Any]) -> str:
        """Format report into printable standalone HTML."""
        study_id = report_data["study_id"]
        pred = report_data["predictive_model_evaluation"]
        lesion = report_data["lesion_morphometry"]
        regions = report_data["roi_analysis"]["regions"]
        net = report_data["roi_analysis"]["network_summary"]

        rows_html = "".join([
            f"""<tr>
                <td style='padding:8px; border:1px solid #e2e8f0;'><b>{r['name']}</b> ({r['brodmann']})</td>
                <td style='padding:8px; border:1px solid #e2e8f0;'>{r['roi_volume_cm3']} cm³</td>
                <td style='padding:8px; border:1px solid #e2e8f0;'>{r['overlap_volume_cm3']} cm³</td>
                <td style='padding:8px; border:1px solid #e2e8f0; font-weight:600;'>{r['overlap_percentage']}%</td>
                <td style='padding:8px; border:1px solid #e2e8f0;'>{r['severity']}</td>
            </tr>"""
            for r in regions
        ])

        return f"""<!DOCTYPE html>
<html>
<head>
    <title>NeuroLens AI Research Report - {study_id}</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; margin: 40px; color: #1e293b; background: #fff; }}
        h1, h2, h3 {{ color: #0f172a; margin-bottom: 6px; }}
        .header {{ border-bottom: 2px solid #3b82f6; padding-bottom: 16px; margin-bottom: 24px; }}
        .badge {{ display: inline-block; padding: 4px 10px; border-radius: 6px; font-weight: 600; font-size: 14px; background: #e0f2fe; color: #0369a1; }}
        .metric-card {{ background: #f8fafc; border: 1px solid #e2e8f0; padding: 16px; border-radius: 8px; margin-bottom: 16px; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 12px; font-size: 13px; }}
        th {{ background: #f1f5f9; text-align: left; padding: 8px; border: 1px solid #e2e8f0; }}
        .disclaimer {{ background: #fffbeb; border: 1px solid #fef3c7; color: #92400e; padding: 14px; border-radius: 8px; margin-top: 30px; font-size: 12px; }}
    </style>
</head>
<body>
    <div class="header">
        <h1>NeuroLens AI — Research Case Report</h1>
        <p style="margin:0; color:#64748b;">Study ID: <b>{study_id}</b> | Generated: {report_data['generated_at']}</p>
    </div>

    <div class="metric-card">
        <h2>Language Outcome Prediction (Western Aphasia Battery)</h2>
        <p style="font-size:24px; font-weight:bold; color:#2563eb; margin:8px 0;">
            Predicted WAB-AQ: {pred.get('predicted_wab_aq')} / 100
        </p>
        <p><b>95% Prediction Interval:</b> [{pred.get('uncertainty_interval_95', {}).get('lower')} – {pred.get('uncertainty_interval_95', {}).get('upper')}]</p>
        <p><b>Impairment Classification:</b> <span class="badge">{pred.get('impairment_category')}</span></p>
        <p style="font-size:13px; color:#475569;"><b>Clinical Interpretation:</b> {pred.get('clinical_implication')}</p>
        <p style="font-size:12px; color:#94a3b8;">Model Pipeline: {pred.get('model_type')} ({pred.get('model_version')})</p>
    </div>

    <div class="metric-card">
        <h3>Stroke Lesion Morphometry</h3>
        <p><b>Total Lesion Volume:</b> {lesion.get('total_lesion_volume_cm3')} cm³ ({lesion.get('total_lesion_voxels')} voxels)</p>
        <p><b>Hemispheric Distribution:</b> Left: {lesion.get('left_hemisphere_vol_cm3')} cm³ | Right: {lesion.get('right_hemisphere_vol_cm3')} cm³</p>
        <p><b>Laterality Index:</b> {lesion.get('laterality_index')} ({lesion.get('laterality_label')})</p>
        <p><b>Center of Gravity (MNI):</b> {lesion.get('center_of_gravity_mni')}</p>
    </div>

    <div class="metric-card">
        <h3>Anatomical Language Region Involvement</h3>
        <p>Broca's Complex Load: <b>{net.get('broca_complex_mean_pct')}%</b> | Wernicke's Territory Load: <b>{net.get('wernicke_area_mean_pct')}%</b> | Parietal Conduction Load: <b>{net.get('parietal_conduction_mean_pct')}%</b></p>
        <table>
            <thead>
                <tr>
                    <th>Anatomical Region</th>
                    <th>ROI Volume</th>
                    <th>Lesion Infiltration</th>
                    <th>% Damage</th>
                    <th>Involvement Tier</th>
                </tr>
            </thead>
            <tbody>
                {rows_html}
            </tbody>
        </table>
    </div>

    <div class="disclaimer">
        <b>SCIENTIFIC DISCLAIMER:</b> {report_data['scientific_disclaimer']}
    </div>
</body>
</html>"""

report_generator = ResearchReportGenerator()
